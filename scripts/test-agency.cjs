/* Agency onboarding through the real production bundle with the native API edge
   stubbed. Exercises code verification, stale responses, eligibility recovery and
   the boundary between agency membership and approved host capability. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
const artifacts = path.join(os.tmpdir(), 'binzolive-agency-checks');
fs.mkdirSync(artifacts, { recursive: true });
const member = { user: { id: 'agency-member', name: 'Agency Applicant', role: 'sender', serverRole: 'user', hostStatus: 'none', adultConfirmed: true, languages: ['English'], about: 'I enjoy acoustic music and thoughtful conversations.' }, verification: 'none', requiresOnboarding: false };
const empty = { agency: null, hostStatus: 'none', isVerifiedHost: false, eligible: true, requirements: [], nextStep: 'agency' };
const verified = { ...empty, agency: { id: 'agency-1', name: 'Dream Star Agency', recruitmentCode: 'BINZO7K9Q2M', status: 'ACTIVE' }, joiningCode: 'BINZO7K9Q2M8X4R', codeType: 'host-invite', canJoin: true, nextStep: 'application' };

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
    page.on('pageerror', error => errors.push(error.message));
    await page.route('https://**/*', route => route.abort());
    await page.addInitScript(() => { window.__messages = []; window.ReactNativeWebView = { postMessage: raw => window.__messages.push(JSON.parse(raw)) }; });
    await page.goto(pathToFileURL(path.join(root, 'assets/aurora.html')).href);
    const receive = (type, data = {}) => page.evaluate(message => Native.receive(message), { type, data });
    const latest = type => page.evaluate(key => window.__messages.filter(item => item.type === key).at(-1)?.data, type);
    await receive('session', member);
    await page.evaluate(() => go('settings'));
    await page.getByRole('button', { name: 'Become a Host', exact: true }).click();
    assert.equal(await page.evaluate(() => S.v), 'agency');
    assert.equal(await page.getByRole('status', { name: 'Loading your agency' }).count(), 1);
    const load = await latest('agency.load');
    await receive('agency.loaded', { ...empty, requestId: load.requestId });
    await page.screenshot({ path: path.join(artifacts, 'agency-code-light.png') });
    assert.equal(await page.locator('#nav').isVisible(), false, 'Agency is a detail page with Back');
    await page.getByRole('button', { name: 'Verify joining code', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Enter your one-time host joining code' }).waitFor();
    assert.equal(await latest('agency.verify'), undefined, 'Empty codes stay in the form');
    await page.getByLabel('Host joining code').fill('BINZO7K9Q2M');
    await page.getByRole('button', { name: 'Verify joining code', exact: true }).click();
    let common = await latest('agency.verify');
    await receive('agency.verified', { ...verified, joiningCode: null, codeType: 'agency', canJoin: false, eligible: false, requirements: ['Ask your agency for an individual one-time host joining code.'], requestId: common.requestId });
    assert.equal(await page.getByRole('button', { name: 'Join agency & continue', exact: true }).isDisabled(), true, 'Public agency identity cannot grant membership');
    await page.evaluate(() => zagJoin());
    assert.equal(await latest('agency.join'), undefined);
    await page.getByText('Agency ID: BINZO7K9Q2M', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => ZimiAgency.linked()), false);
    await page.getByLabel('Host joining code').fill('binzo7k9q2m8x4r');
    await page.getByRole('button', { name: 'Verify joining code', exact: true }).click();
    const first = await latest('agency.verify');
    assert.equal(first.agencyCode, 'BINZO7K9Q2M8X4R');
    assert.equal(await page.getByRole('button', { name: 'Verifying…', exact: true }).isDisabled(), true);
    await receive('agency.verified', { ...verified, requestId: first.requestId - 1 });
    assert.equal(await page.getByRole('heading', { name: 'Dream Star Agency' }).count(), 0, 'Stale verification cannot unlock a join');
    await receive('agency.error', { action: 'agency.verify', message: 'This host joining code has already been used.', requestId: first.requestId });
    await page.getByRole('alert').filter({ hasText: 'This host joining code has already been used.' }).waitFor();
    assert.equal(await page.getByLabel('Host joining code').inputValue(), 'BINZO7K9Q2M8X4R');
    assert.equal(await page.evaluate(() => ZimiAgency.linked()), false);
    await page.getByRole('button', { name: 'Verify joining code', exact: true }).click();
    let refused = await latest('agency.verify');
    await receive('agency.error', { action: 'agency.verify', message: 'Invalid host joining code. Ask your agency for a new code.', requestId: refused.requestId });
    await page.getByRole('alert').filter({ hasText: 'Invalid host joining code.' }).waitFor();
    await page.getByRole('button', { name: 'Verify joining code', exact: true }).click();
    refused = await latest('agency.verify');
    await receive('agency.error', { action: 'agency.verify', message: 'Your agency revoked this host joining code.', requestId: refused.requestId });
    await page.getByRole('alert').filter({ hasText: 'Your agency revoked this host joining code.' }).waitFor();
    await page.getByRole('button', { name: 'Verify joining code', exact: true }).click();
    let request = await latest('agency.verify');
    await receive('agency.verified', { ...verified, requestId: request.requestId });
    await page.screenshot({ path: path.join(artifacts, 'agency-confirm-light.png') });
    await page.getByRole('heading', { name: 'Dream Star Agency' }).waitFor();
    assert.equal(await page.evaluate(() => ZimiAgency.linked()), false, 'Verification previews identity without consuming or joining');
    assert.equal(await latest('agency.join'), undefined, 'Verification never sends activation');
    await page.getByLabel('Host joining code').fill('BINZO8K9Q2M8X4R');
    assert.equal(await page.getByRole('button', { name: 'Join agency & continue', exact: true }).isVisible(), false, 'Editing a verified code requires verification again');
    await receive('agency.verified', { ...verified, requestId: request.requestId });
    assert.equal(await page.getByRole('button', { name: 'Join agency & continue', exact: true }).isVisible(), false, 'An old preview cannot reappear after editing its code');
    await page.getByLabel('Host joining code').fill('BINZO7K9Q2M8X4R');
    await page.getByRole('button', { name: 'Verify joining code', exact: true }).click();
    request = await latest('agency.verify');
    await receive('agency.verified', { ...verified, requestId: request.requestId });
    await page.getByRole('button', { name: 'Join agency & continue', exact: true }).click();
    const join = await latest('agency.join');
    assert.equal(join.agencyCode, 'BINZO7K9Q2M8X4R');
    assert.notEqual(join.agencyCode, verified.agency.recruitmentCode, 'Activation uses the personal invite, never the agency identity');
    assert.equal(await page.getByRole('button', { name: 'Joining agency…', exact: true }).isDisabled(), true);
    await receive('agency.error', { action: 'agency.join', message: 'The response could not be confirmed. Retry your joining code.', requestId: join.requestId });
    await page.getByRole('button', { name: 'Join agency & continue', exact: true }).click();
    const retry = await latest('agency.join');
    assert.equal(retry.agencyCode, join.agencyCode, 'A lost claim response retries the same one-time code for the same authenticated user');
    await receive('agency.joined', { ...verified, requestId: retry.requestId });
    await page.getByText('Your used joining code:', { exact: false }).waitFor();
    assert.equal(await page.locator('.za-joined-code strong').innerText(), 'BINZO7K9Q2M8X4R');
    assert.equal(await page.locator('.za-agency p').innerText(), 'Agency ID: BINZO7K9Q2M');
    assert.equal(await page.evaluate(() => isApprovedHost()), false, 'Agency membership must not grant host access');
    await page.getByRole('button', { name: 'Continue host application', exact: true }).click();
    assert.equal(await page.evaluate(() => S.v), 'kyc');
    await page.locator('#kf_bio').fill('I share acoustic music and enjoy thoughtful conversations.');
    await page.getByRole('button', { name: 'Submit for review', exact: true }).click();
    assert.ok(await latest('verification.submit'), 'Application reaches native bridge after membership');
    await receive('verification.status', { status: 'pending' });
    assert.equal(await page.evaluate(() => isApprovedHost()), false);
    await page.evaluate(() => ZimiAgency.open('settings'));
    request = await latest('agency.load');
    await receive('agency.loaded', { ...verified, hostStatus: 'pending', nextStep: 'review', requestId: request.requestId });
    await page.getByRole('heading', { name: 'Your application is under review' }).waitFor();
    await page.screenshot({ path: path.join(artifacts, 'agency-review-light.png') });
    assert.equal(await page.getByLabel('Host joining code').count(), 0, 'Joined members cannot switch agencies in-app');
    await page.setViewportSize({ width: 320, height: 740 });
    await page.evaluate(() => ZimiThemes.setDark(true));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: path.join(artifacts, 'agency-review-dark-320.png') });
    await page.evaluate(() => zagLoad());
    request = await latest('agency.load');
    await receive('agency.error', { action: 'agency.load', message: 'Agency details are temporarily unavailable.', requestId: request.requestId });
    await page.getByRole('alert').filter({ hasText: 'Agency details are temporarily unavailable.' }).waitFor();
    assert.equal(await page.getByRole('heading', { name: 'Dream Star Agency' }).count(), 1, 'Reload failure preserves last-known membership and offers retry');
    await page.getByRole('button', { name: 'Try again', exact: true }).click();
    request = await latest('agency.load');
    await receive('agency.loaded', { ...verified, hostStatus: 'pending', nextStep: 'review', requestId: request.requestId });

    // Old/skipped profiles have a reachable, server-backed age confirmation route.
    await receive('session', { ...member, user: { ...member.user, id: 'legacy-member', adultConfirmed: false } });
    assert.equal(await page.evaluate(() => ZimiAgency.linked()), false, 'A replacement account cannot inherit the previous membership');
    await page.evaluate(() => ZimiAgency.open('profile'));
    request = await latest('agency.load');
    await receive('agency.loaded', { ...empty, eligible: false, requirements: ['Confirm you are at least 18 in your profile'], requestId: request.requestId });
    await page.getByRole('button', { name: 'Complete profile & confirm age', exact: true }).click();
    assert.equal(await page.evaluate(() => S.auth.creatorIntent), true);
    assert.equal(await page.evaluate(() => S.auth.step), 'profile');
    assert.equal(await page.evaluate(() => S.auth.verified), true, 'Existing authenticated profile recovery does not ask for OTP again');
    assert.equal(await page.getByRole('checkbox', { name: /18/ }).count(), 1);
    await receive('session', { ...member, user: { ...member.user, id: 'existing-host', role: 'host', serverRole: 'host', hostStatus: 'approved', isVerifiedHost: true }, verification: 'verified' });
    assert.equal(await page.evaluate(() => isApprovedHost()), true, 'Existing approved hosts retain access without local agency state');
    assert.equal(await page.evaluate(() => S.v), 'home');
    assert.deepEqual(errors, []);
    console.log(`PASS agency onboarding: code/errors/stale requests, membership/apply boundary, review, age recovery, legacy approval, light/dark 320/390px. Screenshots: ${artifacts}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
